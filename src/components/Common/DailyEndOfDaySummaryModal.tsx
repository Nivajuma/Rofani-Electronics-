import React, { useMemo, useState } from 'react';
import {
  X,
  Clock,
  TrendingUp,
  Wallet,
  Smartphone,
  CreditCard,
  Receipt,
  Package,
  Copy,
  Check,
  Share2,
  MessageCircle,
  ShieldCheck,
} from 'lucide-react';
import { Expense, RestockRecord, Transaction } from '../../types';

interface DailyEndOfDaySummaryModalProps {
  isOpen: boolean;
  onClose: () => void;
  onDismissForToday: () => void;
  storeName: string;
  transactions: Transaction[];
  expenses: Expense[];
  restockRecords: RestockRecord[];
  canViewProfit: boolean;
}

const getTodayKey = () => {
  const d = new Date();
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${y}-${m}-${day}`;
};

const isSameLocalDay = (isoOrNum: string | number | undefined, todayKey: string): boolean => {
  if (!isoOrNum) return false;
  const dt = new Date(isoOrNum);
  if (isNaN(dt.getTime())) return false;
  const y = dt.getFullYear();
  const m = String(dt.getMonth() + 1).padStart(2, '0');
  const day = String(dt.getDate()).padStart(2, '0');
  return `${y}-${m}-${day}` === todayKey;
};

export const DailyEndOfDaySummaryModal: React.FC<DailyEndOfDaySummaryModalProps> = ({
  isOpen,
  onClose,
  onDismissForToday,
  storeName,
  transactions,
  expenses,
  restockRecords,
  canViewProfit,
}) => {
  const [copied, setCopied] = useState(false);
  const todayKey = getTodayKey();

  const summary = useMemo(() => {
    const todayTx = transactions.filter((t) => isSameLocalDay(t.date || t.timestamp, todayKey));
    const totalSales = todayTx.reduce((s, t) => s + (t.grandTotal || 0), 0);
    const salesCount = todayTx.length;

    let cashTotal = 0;
    let mpesaTotal = 0;
    let cardBankTotal = 0;
    let creditUnpaidTotal = 0;
    let totalCostOfGoods = 0;

    todayTx.forEach((tx) => {
      if (tx.payments && tx.payments.length > 0) {
        tx.payments.forEach((p) => {
          if (p.method === 'cash') cashTotal += p.amount || 0;
          else if (p.method === 'mpesa') mpesaTotal += p.amount || 0;
          else cardBankTotal += p.amount || 0;
        });
      } else if ((tx as any).paymentMethod === 'mpesa') {
        mpesaTotal += tx.amountPaid || 0;
      } else {
        cashTotal += tx.amountPaid || 0;
      }
      creditUnpaidTotal += Math.max(0, tx.balanceDue || 0);

      (tx.items || []).forEach((it) => {
        const cost = Number(it.product?.costPrice) || 0;
        const qty = (it.quantity || 0) + (it.freeQuantity || 0);
        totalCostOfGoods += cost * qty;
      });
    });

    const todayExp = expenses.filter((e) => isSameLocalDay(e.date, todayKey));
    const totalExpenses = todayExp.reduce((s, e) => s + (e.amount || 0), 0);

    const todayRestocks = restockRecords.filter((r) => isSameLocalDay(r.date, todayKey));
    const totalStockInCost = todayRestocks.reduce((s, r) => s + (r.totalCost || 0), 0);
    const totalStockInUnits = todayRestocks.reduce((s, r) => s + (r.quantityAdded || 0), 0);

    const grossProfit = totalSales - totalCostOfGoods;
    const netProfit = grossProfit - totalExpenses;

    return {
      salesCount,
      totalSales,
      cashTotal,
      mpesaTotal,
      cardBankTotal,
      creditUnpaidTotal,
      totalExpenses,
      expensesCount: todayExp.length,
      totalStockInCost,
      totalStockInUnits,
      grossProfit,
      netProfit,
    };
  }, [transactions, expenses, restockRecords, todayKey]);

  if (!isOpen) return null;

  const cleanStoreName = (storeName || 'Rofani POS').trim() || 'Rofani POS';
  const readableDate = new Date().toLocaleDateString('en-KE', {
    weekday: 'short',
    day: 'numeric',
    month: 'short',
    year: 'numeric',
  });

  const shareText =
    `📊 9:00 PM Daily Shop Summary — ${cleanStoreName}\n` +
    `📅 Date: ${readableDate}\n\n` +
    `• Total Sales (${summary.salesCount} receipts): KSh ${summary.totalSales.toLocaleString()}\n` +
    `• Cash Collected: KSh ${summary.cashTotal.toLocaleString()}\n` +
    `• M-Pesa Collected: KSh ${summary.mpesaTotal.toLocaleString()}\n` +
    (summary.cardBankTotal > 0 ? `• Card / Bank: KSh ${summary.cardBankTotal.toLocaleString()}\n` : '') +
    (summary.creditUnpaidTotal > 0 ? `• Credit / Unpaid: KSh ${summary.creditUnpaidTotal.toLocaleString()}\n` : '') +
    `• Today's Expenses (${summary.expensesCount}): KSh ${summary.totalExpenses.toLocaleString()}\n` +
    `• Today's Stock-In (${summary.totalStockInUnits} units): KSh ${summary.totalStockInCost.toLocaleString()}\n` +
    (canViewProfit ? `• Net Profit Estimate: KSh ${summary.netProfit.toLocaleString()}\n` : '') +
    `\nGenerated by Rofani POS`;

  const handleCopy = () => {
    if (typeof navigator !== 'undefined' && navigator.clipboard) {
      navigator.clipboard.writeText(shareText).catch(() => {});
    }
    setCopied(true);
    setTimeout(() => setCopied(false), 2400);
  };

  const handleNativeShare = async () => {
    if (typeof navigator !== 'undefined' && typeof navigator.share === 'function') {
      try {
        await navigator.share({
          title: `Daily Summary — ${cleanStoreName} (${readableDate})`,
          text: shareText,
        });
        return;
      } catch {
        // fallback to clipboard
      }
    }
    handleCopy();
  };

  const whatsappUrl = `https://wa.me/?text=${encodeURIComponent(shareText)}`;

  return (
    <div
      className="fixed inset-0 z-[280] bg-black/80 backdrop-blur-sm flex items-center justify-center p-4"
      onClick={onClose}
    >
      <div
        className="w-full max-w-lg bg-slate-900 border border-slate-700/80 rounded-2xl shadow-2xl overflow-hidden flex flex-col max-h-[92vh]"
        onClick={(e) => e.stopPropagation()}
      >
        {/* Header */}
        <div className="px-5 py-4 bg-slate-950/90 border-b border-slate-800 flex items-center justify-between">
          <div className="flex items-center gap-3 min-w-0">
            <div className="w-10 h-10 rounded-xl bg-amber-500/15 border border-amber-500/35 text-amber-400 flex items-center justify-center shrink-0">
              <Clock className="w-5 h-5" />
            </div>
            <div className="min-w-0">
              <h3 className="text-sm font-extrabold text-white truncate">9:00 PM Daily Summary</h3>
              <p className="text-[11px] text-slate-400 truncate">
                {cleanStoreName} • {readableDate}
              </p>
            </div>
          </div>
          <button
            type="button"
            onClick={onClose}
            className="w-8 h-8 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-300 hover:text-white flex items-center justify-center transition cursor-pointer shrink-0"
            aria-label="Close summary"
          >
            <X className="w-4 h-4" />
          </button>
        </div>

        {/* Summary Cards Grid */}
        <div className="p-5 space-y-4 overflow-y-auto">
          <div className="bg-slate-950 border border-emerald-500/30 rounded-2xl p-4 flex items-center justify-between gap-3">
            <div>
              <div className="text-[11px] font-bold uppercase tracking-wider text-slate-400">
                Today&apos;s Total Sales
              </div>
              <div className="text-2xl font-black text-emerald-400 tabular-nums mt-0.5">
                KSh {summary.totalSales.toLocaleString()}
              </div>
              <div className="text-[11px] text-slate-400 mt-0.5">
                {summary.salesCount} {summary.salesCount === 1 ? 'sale' : 'sales'} recorded today
              </div>
            </div>
            <div className="w-12 h-12 rounded-xl bg-emerald-500/15 border border-emerald-500/30 flex items-center justify-center text-emerald-400 shrink-0">
              <TrendingUp className="w-6 h-6" />
            </div>
          </div>

          <div className="grid grid-cols-2 gap-2.5">
            <div className="bg-slate-800/80 border border-slate-700/70 rounded-xl p-3">
              <div className="flex items-center gap-1.5 text-[11px] text-slate-400 font-semibold">
                <Wallet className="w-3.5 h-3.5 text-emerald-400" />
                <span>Cash Collected</span>
              </div>
              <div className="text-sm font-extrabold text-white tabular-nums mt-1">
                KSh {summary.cashTotal.toLocaleString()}
              </div>
            </div>

            <div className="bg-slate-800/80 border border-slate-700/70 rounded-xl p-3">
              <div className="flex items-center gap-1.5 text-[11px] text-slate-400 font-semibold">
                <Smartphone className="w-3.5 h-3.5 text-sky-400" />
                <span>M-Pesa Collected</span>
              </div>
              <div className="text-sm font-extrabold text-white tabular-nums mt-1">
                KSh {summary.mpesaTotal.toLocaleString()}
              </div>
            </div>

            <div className="bg-slate-800/80 border border-slate-700/70 rounded-xl p-3">
              <div className="flex items-center gap-1.5 text-[11px] text-slate-400 font-semibold">
                <Receipt className="w-3.5 h-3.5 text-rose-400" />
                <span>Today&apos;s Expenses</span>
              </div>
              <div className="text-sm font-extrabold text-rose-300 tabular-nums mt-1">
                KSh {summary.totalExpenses.toLocaleString()}
              </div>
            </div>

            <div className="bg-slate-800/80 border border-slate-700/70 rounded-xl p-3">
              <div className="flex items-center gap-1.5 text-[11px] text-slate-400 font-semibold">
                <Package className="w-3.5 h-3.5 text-indigo-400" />
                <span>Today&apos;s Stock-In</span>
              </div>
              <div className="text-sm font-extrabold text-indigo-300 tabular-nums mt-1">
                KSh {summary.totalStockInCost.toLocaleString()}
              </div>
              <div className="text-[10px] text-slate-400">{summary.totalStockInUnits} units added</div>
            </div>
          </div>

          {(summary.cardBankTotal > 0 || summary.creditUnpaidTotal > 0) && (
            <div className="grid grid-cols-2 gap-2.5">
              {summary.cardBankTotal > 0 && (
                <div className="bg-slate-950/70 border border-slate-800 rounded-xl p-3">
                  <div className="flex items-center gap-1.5 text-[11px] text-slate-400 font-semibold">
                    <CreditCard className="w-3.5 h-3.5 text-sky-400" />
                    <span>Card / Bank</span>
                  </div>
                  <div className="text-sm font-bold text-slate-100 tabular-nums mt-1">
                    KSh {summary.cardBankTotal.toLocaleString()}
                  </div>
                </div>
              )}
              {summary.creditUnpaidTotal > 0 && (
                <div className="bg-slate-950/70 border border-amber-500/30 rounded-xl p-3">
                  <div className="text-[11px] text-amber-300 font-semibold">Credit Given Today</div>
                  <div className="text-sm font-bold text-amber-200 tabular-nums mt-1">
                    KSh {summary.creditUnpaidTotal.toLocaleString()}
                  </div>
                </div>
              )}
            </div>
          )}

          {canViewProfit && (
            <div className="bg-slate-950 border border-slate-800 rounded-xl p-3.5 flex items-center justify-between">
              <div className="flex items-center gap-2 text-xs text-slate-300 font-semibold">
                <ShieldCheck className="w-4 h-4 text-emerald-400 shrink-0" />
                <span>Estimated Net Profit (after COGS &amp; Expenses)</span>
              </div>
              <span
                className={`text-sm font-black tabular-nums ${
                  summary.netProfit >= 0 ? 'text-emerald-400' : 'text-rose-400'
                }`}
              >
                KSh {summary.netProfit.toLocaleString()}
              </span>
            </div>
          )}
        </div>

        {/* Footer Actions */}
        <div className="p-4 bg-slate-950/90 border-t border-slate-800 space-y-2.5">
          <div className="grid grid-cols-3 gap-2">
            <a
              href={whatsappUrl}
              target="_blank"
              rel="noopener noreferrer"
              className="py-2.5 px-3 rounded-xl bg-emerald-600 hover:bg-emerald-500 text-white text-xs font-bold flex items-center justify-center gap-1.5 transition whitespace-nowrap"
            >
              <MessageCircle className="w-3.5 h-3.5" />
              <span>WhatsApp</span>
            </a>
            <button
              type="button"
              onClick={handleCopy}
              className="py-2.5 px-3 rounded-xl bg-slate-800 hover:bg-slate-700 border border-slate-700 text-slate-100 text-xs font-bold flex items-center justify-center gap-1.5 transition cursor-pointer whitespace-nowrap"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5 text-sky-400" />}
              <span>{copied ? 'Copied' : 'Copy'}</span>
            </button>
            <button
              type="button"
              onClick={handleNativeShare}
              className="py-2.5 px-3 rounded-xl bg-sky-600 hover:bg-sky-500 text-white text-xs font-bold flex items-center justify-center gap-1.5 transition cursor-pointer whitespace-nowrap"
            >
              <Share2 className="w-3.5 h-3.5" />
              <span>Share</span>
            </button>
          </div>

          <button
            type="button"
            onClick={onDismissForToday}
            className="w-full py-2 rounded-xl bg-slate-800/80 hover:bg-slate-800 text-slate-300 hover:text-white text-xs font-semibold transition cursor-pointer"
          >
            Dismiss Summary for Today
          </button>
        </div>
      </div>
    </div>
  );
};
